const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const base = process.env.BASE || 'http://127.0.0.1:8000/chart';
  const pfx = process.env.PFX || 'g4';
  await page.goto(base, { waitUntil: 'networkidle', timeout: 60000 });
  await page.evaluate(() => localStorage.setItem('horoscope-language','en'));
  await page.reload({ waitUntil: 'networkidle' });
  await page.click('#example'); await page.waitForTimeout(400);
  await page.click('#calculate');
  await page.waitForSelector('#scr-app:not([hidden])', { timeout: 90000 });
  await page.waitForTimeout(2000);
  await page.evaluate(() => document.querySelector('.outcome-card[data-topic=love]')?.scrollIntoView({block:'start'}));
  await page.waitForTimeout(600);
  await page.screenshot({ path: `/tmp/${pfx}-cards-en.png` });
  await page.evaluate(() => document.querySelector('.outcome-card[data-topic=children] summary')?.click());
  await page.waitForTimeout(500);
  await page.evaluate(() => document.querySelector('.outcome-card[data-topic=children]')?.scrollIntoView({block:'start'}));
  await page.waitForTimeout(400);
  await page.screenshot({ path: `/tmp/${pfx}-children-open-en.png` });
  await page.click('[data-language=ta]'); await page.waitForTimeout(1000);
  await page.evaluate(() => document.querySelector('.outcome-card[data-topic=love]')?.scrollIntoView({block:'start'}));
  await page.waitForTimeout(600);
  await page.screenshot({ path: `/tmp/${pfx}-cards-ta.png` });
  await page.evaluate(() => document.querySelector('.outcome-card[data-topic=children] summary')?.click());
  await page.waitForTimeout(500);
  await page.evaluate(() => document.querySelector('.outcome-card[data-topic=children]')?.scrollIntoView({block:'start'}));
  await page.waitForTimeout(400);
  await page.screenshot({ path: `/tmp/${pfx}-children-open-ta.png` });
  await browser.close(); console.log('done');
})().catch(e => { console.error(e.message); process.exit(1); });
