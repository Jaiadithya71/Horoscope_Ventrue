const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const base = process.env.BASE || 'http://127.0.0.1:8000/chart';
  const pfx = process.env.PFX || 'm1';
  await page.goto(base, { waitUntil: 'networkidle', timeout: 60000 });
  await page.evaluate(() => localStorage.setItem('horoscope-language','en'));
  await page.reload({ waitUntil: 'networkidle' });
  await page.click('#example'); await page.waitForTimeout(400);
  await page.click('#calculate');
  await page.waitForSelector('#scr-app:not([hidden])', { timeout: 90000 });
  await page.waitForTimeout(2000);
  await page.evaluate(() => document.querySelector('#match-sec')?.scrollIntoView({block:'start'}));
  await page.waitForTimeout(500);
  await page.click('#match-open'); await page.waitForTimeout(400);
  await page.evaluate(() => document.querySelector('#match-form')?.scrollIntoView({block:'start'}));
  await page.waitForTimeout(400);
  await page.screenshot({ path: `/tmp/${pfx}-form.png` });
  await page.fill('#match-form [name=mdate]', '2001-05-15');
  await page.fill('#match-form [name=mtime]', '08:45');
  await page.click('#match-form details.manual summary');
  await page.fill('#match-form [name=mlat]', '11.6643');
  await page.fill('#match-form [name=mlon]', '78.146');
  await page.selectOption('#match-form [name=mtimezone]', 'Asia/Kolkata');
  await page.click('#match-calc');
  await page.waitForSelector('#match-result .dosha-row', { timeout: 90000 });
  await page.waitForTimeout(1200);
  await page.evaluate(() => document.querySelector('#match-result')?.scrollIntoView({block:'start'}));
  await page.waitForTimeout(500);
  await page.screenshot({ path: `/tmp/${pfx}-result.png` });
  await page.click('[data-language=ta]'); await page.waitForTimeout(900);
  await page.evaluate(() => document.querySelector('#match-result')?.scrollIntoView({block:'start'}));
  await page.waitForTimeout(400);
  await page.screenshot({ path: `/tmp/${pfx}-result-ta.png` });
  await browser.close(); console.log('done');
})().catch(e => { console.error(e.message); process.exit(1); });
